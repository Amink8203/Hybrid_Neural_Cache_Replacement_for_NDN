"""Verify checkpoint/trace provenance and replay all submitted test results."""
from __future__ import annotations

import csv
import hashlib
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import torch

from ndn_cache.agent import NeuralCacheAgent
from ndn_cache.baselines import BaselineCacheController
from ndn_cache.checkpoint import load_checkpoint
from ndn_cache.cli import _trace_sha256
from ndn_cache.topology import TopologySimulator, build_topology
from ndn_cache.training import split_trace
from ndn_cache.utils import seed_everything
from ndn_cache.workload import SyntheticWorkloadConfig, generate_synthetic_trace


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def main() -> int:
    artifacts = ROOT / "artifacts"
    report = json.loads((artifacts / "report.json").read_text(encoding="utf-8"))
    with (artifacts / "summary.csv").open(encoding="utf-8", newline="") as stream:
        rows = {(r["topology"], r["policy"]): r for r in csv.DictReader(stream)}
    require(len(rows) == 20, "summary.csv must contain four topologies and five policies")
    torch.set_num_threads(1)
    seed = report["trace"]["seed"]
    seed_everything(seed)
    trace = generate_synthetic_trace(SyntheticWorkloadConfig(**report["trace"]["synthetic_config"]))
    require(_trace_sha256(trace) == report["trace"]["sha256"], "full trace digest mismatch")
    total = len(trace)
    partitions = split_trace(
        trace,
        train_fraction=report["trace"]["train_requests"] / total,
        validation_fraction=report["trace"]["validation_requests"] / total,
    )
    for name, partition in zip(["train", "validation", "test"], partitions):
        require(len(partition) == report["trace"][f"{name}_requests"], f"{name} split size mismatch")
        require(_trace_sha256(partition) == report["trace"]["partition_digests"][name],
                f"{name} split digest mismatch")
    print("Verified original trace and all three partition digests.", flush=True)
    metric_fields = ("cache_hit_ratio", "byte_cache_hit_ratio", "cache_hit_requests",
                     "producer_fetches", "mean_retrieval_hops", "interest_hops", "data_hops",
                     "router_lookups", "router_cache_hits", "router_cache_misses")
    for kind in ["line", "ring", "star", "mesh"]:
        saved = report["topologies"][kind]
        individual = json.loads((artifacts / f"{kind}_report.json").read_text(encoding="utf-8"))
        # The combined report was generated by reusing completed checkpoints;
        # individual reports came from the original training processes.
        original = {k: v for k, v in individual["topologies"][kind].items() if k != "resumed"}
        combined = {k: v for k, v in saved.items() if k != "resumed"}
        require(original == combined, f"{kind} individual report mismatch")
        for checkpoint_key, filename in [("checkpoint", f"{kind}.pt"),
                                         ("pretrained_checkpoint", f"{kind}-pretrained.pt")]:
            path = artifacts / "models" / filename
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            require(digest == saved[checkpoint_key]["sha256"], f"{filename} SHA-256 mismatch")
        seed_everything(seed)
        model, training, metadata = load_checkpoint(artifacts / "models" / f"{kind}.pt")
        require(training is not None, f"{kind} lacks training configuration")
        require(metadata["partition_digests"] == report["trace"]["partition_digests"],
                f"{kind} checkpoint partition metadata mismatch")
        network = report["network"]
        topology = build_topology(kind, num_nodes=network["routers"],
                                  producer_node=network["producer_node"],
                                  producer_prefix=network["producer_prefix"],
                                  star_center=network["star_center"])
        controllers = {
            "neural": NeuralCacheAgent(model, training,
                cache_items=report["cache"]["items_per_router"],
                cache_bytes=report["cache"]["bytes_per_router"], seed=seed),
            **{policy: BaselineCacheController(policy,
                cache_items=report["cache"]["items_per_router"],
                cache_bytes=report["cache"]["bytes_per_router"], seed=seed)
               for policy in ["lru", "lfu", "fifo", "random"]},
        }
        for policy, controller in controllers.items():
            metrics = TopologySimulator(topology, controller).run(partitions[2]).metrics.as_dict()
            recorded = (saved["neural_test"] if policy == "neural" else saved["baselines"][policy])["network_metrics"]
            for field in metric_fields:
                require(math.isclose(metrics[field], recorded[field], rel_tol=0.0, abs_tol=1e-12),
                        f"{kind}/{policy} {field}: {metrics[field]} != {recorded[field]}")
            for csv_field, metric_field in [("request_hit_ratio", "cache_hit_ratio"),
                                            ("byte_hit_ratio", "byte_cache_hit_ratio"),
                                            ("cache_hits", "cache_hit_requests"),
                                            ("producer_fetches", "producer_fetches"),
                                            ("mean_retrieval_hops", "mean_retrieval_hops")]:
                require(math.isclose(float(rows[(kind, policy)][csv_field]), metrics[metric_field],
                                    rel_tol=0.0, abs_tol=1e-12), f"{kind}/{policy} CSV mismatch: {csv_field}")
        print(f"Verified {kind}: two checkpoint hashes and all five policy results.", flush=True)
    print("All 20 saved test results match replay.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
